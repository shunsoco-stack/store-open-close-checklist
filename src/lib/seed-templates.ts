import type { Category, Store, TemplateItem } from "./types.ts";

type Entry = [string, Category, ("check" | "number" | "select")?, string?];
function items(prefix: string, entries: Entry[]): TemplateItem[] {
  return entries.map(([title, category, type = "check", detail = ""], index) => ({
    id: `${prefix}-${index + 1}`,
    title,
    category,
    type,
    required: index !== 10,
    weekdays: detail === "月曜" ? [1] : [],
    min: 0,
    max: 5,
    unit: type === "number" ? "℃" : "",
    options: type === "select" ? ["差異なし", "差異あり"] : [],
  }));
}
