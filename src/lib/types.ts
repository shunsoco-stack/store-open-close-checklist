export type Kind = "open" | "close";
export type Category = "設備" | "衛生" | "レジ" | "防犯／施錠" | "売場" | "その他";
export type TemplateItem = {
  id: string;
  title: string;
  category: Category;
  type: "check" | "number" | "select";
  required: boolean;
  weekdays: number[];
  min: number;
  max: number;
  unit: string;
  options: string[];
};
export type Store = {
  id: string;
  name: string;
  description: string;
  open: string;
  close: string;
  rollover: string;
  openBefore: number;
  closeBefore: number;
  openDeadline: number;
  closeDeadline: number;
  staff: string[];
  templates: Record<Kind, TemplateItem[]>;
};
export type Item = TemplateItem & {
  status: "pending" | "ok" | "issue" | "handover";
  value: string;
  comment: string;
  actor: string;
  at: string;
  photos: string[];
  hadIssue: boolean;
};
export type Check = {
  id: string;
  storeId: string;
  date: string;
  kind: Kind;
  availableAt: string;
  deadline: string;
  items: Item[];
  actor: string;
  changes: { actor: string; at: string }[];
  completedAt: string;
  completedBy: string;
  note: string;
};
export type Handover = {
  id: string;
  storeId: string;
  sourceId: string;
  itemId: string;
  title: string;
  reason: string;
  target: Kind | "manager";
  createdAt: string;
  createdBy: string;
  status: "unread" | "read" | "done";
  acknowledgedBy: string;
  acknowledgedAt: string;
  resolvedBy: string;
  resolvedAt: string;
};
export type Data = { version: 1; stores: Store[]; checks: Check[]; handovers: Handover[] };
export const kindLabel = { open: "開店チェック", close: "閉店チェック" };
export const targetLabel = { ...kindLabel, manager: "店長" };
export const categories: Category[] = ["設備", "衛生", "レジ", "防犯／施錠", "売場", "その他"];
