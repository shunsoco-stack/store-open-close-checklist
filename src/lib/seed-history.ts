export function historyScenario(storeId: string, ago: number, kind: Kind) {
  const day = days[storeId].find((row) => row[0] === ago);
  if (!day) return { staffIndex: 0, note: "本日の確認を終えました。次の担当者へ引き継ぎます。" };
  return {
    staffIndex: kind === "open" ? day[1] : day[2],
    note: kind === "open" ? day[3] : day[4],
  };
}
